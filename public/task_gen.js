// ======================================================
// 1. チェックリスト回答 → 特徴タグ変換ルール
// ======================================================
const featureRules = {
  "やりたいことがわからない": ["興味迷子", "方向性欠如"],
  "自信がない": ["自信不足"],
  "行動できない": ["行動困難"],
  "将来が不安": ["不安"],

  "何から始めればいいかわからない": ["初動困難"],
  "モチベーションが低い": ["低活力"],
  "情報が多すぎて迷う": ["情報過多"],

  "興味の方向性が見える": ["方向性欲求"],
  "自信がつく": ["自己肯定欲求"],
  "小さく行動できる": ["行動欲求"],

  "失敗が怖い": ["失敗恐怖"],
  "続かない": ["継続不安"],
  "他人と比べてしまう": ["比較不安"],

  "コツコツ続けられる": ["継続力"],
  "好奇心がある": ["好奇心"],
  "人の話を聞ける": ["共感力"]
};


// ======================================================
// 2. 特徴抽出（チェックボックスの配列を受け取る）
// ======================================================
function extractFeatures(answers) {
  const features = [];

  for (const answer of answers) {
    if (featureRules[answer]) {
      features.push(...featureRules[answer]);
    }
  }

  return [...new Set(features)];
}


// ======================================================
// 3. ユーザータイプ分類
// ======================================================
function classifyUser(features) {
  if (features.includes("不安") || features.includes("失敗恐怖")) {
    return "不安優位タイプ";
  }
  if (features.includes("興味迷子") || features.includes("方向性欠如")) {
    return "方向性探索タイプ";
  }
  if (features.includes("自信不足")) {
    return "自己肯定タイプ";
  }
  if (features.includes("行動困難") || features.includes("初動困難")) {
    return "行動サポートタイプ";
  }
  return "標準タイプ";
}


// ======================================================
// 4. 大きなタスク生成ルール
// ======================================================
const bigTaskTemplates = {
  "興味迷子": "興味の方向性を仮決めする",
  "方向性欠如": "理想の方向性を1文で定義する",
  "自信不足": "自信の源を特定する",
  "不安": "不安の正体を特定する",
  "行動困難": "行動を阻害している要因を特定する",
  "初動困難": "最初の一歩を作る",
  "強み不明": "自分の強みの核を見つける"
};


// ======================================================
// 5. 大きなタスク生成
// ======================================================
function generateBigTask(features) {
  const priority = [
    "不安",
    "自信不足",
    "興味迷子",
    "方向性欠如",
    "行動困難",
    "初動困難",
    "強み不明"
  ];

  for (const p of priority) {
    if (features.includes(p)) {
      return bigTaskTemplates[p];
    }
  }

  return "現状を整理する";
}


// ======================================================
// 6. 中タスクテンプレート
// ======================================================
const midTaskTemplates = {
  "興味の方向性を仮決めする": [
    "興味の候補を3つ書き出す",
    "その中から1つだけ選ぶ",
    "選んだ理由を1文で書く"
  ],
  "理想の方向性を1文で定義する": [
    "理想の状態を箇条書きで3つ書く",
    "最も大事な1つを選ぶ",
    "それを1文にまとめる"
  ],
  "自信の源を特定する": [
    "過去の成功体験を3つ書く",
    "共通点を探す",
    "自信の源を1つにまとめる"
  ],
  "不安の正体を特定する": [
    "今の不安を書き出す",
    "最も強い不安を選ぶ",
    "その原因を推測する"
  ],
  "行動を阻害している要因を特定する": [
    "行動できない理由を3つ書く",
    "最も大きい理由を選ぶ",
    "その理由を分解する"
  ],
  "最初の一歩を作る": [
    "今日できる最小ステップを決める",
    "5分だけ試す",
    "終わったら感想をメモする"
  ],
  "自分の強みの核を見つける": [
    "自分の強みを3つ書く",
    "強みが役立った瞬間を書く",
    "強みの核を1つにまとめる"
  ],
  "現状を整理する": [
    "今の状態を3つ書く",
    "最も重要な1つを選ぶ",
    "その理由を言語化する"
  ]
};


// ======================================================
// 7. タスクツリー生成
// ======================================================
function buildTaskTree(bigTask) {
  const mids = midTaskTemplates[bigTask];

  return {
    title: bigTask,
    description: "方向性を決めるための大きなタスクです。",
    children: [
      { title: "ステップ1", children: [{ title: mids[0] }] },
      { title: "ステップ2", children: [{ title: mids[1] }] },
      { title: "ステップ3", children: [{ title: mids[2] }] }
    ]
  };
}


// ======================================================
// 8. 全体処理（チェックリスト → 特徴 → タスク）
// ======================================================
function processChecklist(answers) {
  const features = extractFeatures(answers);
  const userType = classifyUser(features);
  const bigTask = generateBigTask(features);
  const taskTree = buildTaskTree(bigTask);

  return {
    answers,
    features,
    userType,
    bigTask,
    taskTree
  };
}